/* 图说 · 规则识别引擎
 *
 * 作用：不吃 API Key，也能把一段中文文字判成「最合适的图型」，并切成结构化数据。
 * 约束：纯函数、无 DOM 依赖，能被浏览器和 node 同时加载（node 侧用于自检）。
 *
 * 设计取舍：这里不是"语言模型"，是一套可复核的中文规则。
 * 每条判断都会把依据（命中了哪些词）一起返回，界面上要能摊开给用户看。
 */
(function (全局) {
  'use strict';

  /* ---------- 词表：改这里就能调整识别口味 ---------- */

  const 序号词 = /^(第[一二三四五六七八九十\d]+步|步骤\s*[一二三四五六七八九十\d]+|首先|其次|再者|然后|接着|跟着|最后|最终|[①②③④⑤⑥⑦⑧⑨⑩⑪⑫]|[一二三四五六七八九十]{1,2}[、.]|\d{1,2}[、.)）])/;
  const 词_流程 = /流程|步骤|第一步|先.{0,8}再|然后|接着|最后|路线|工序|动作/;
  const 词_时间 = /里程碑|时间线|阶段|规划|回顾|从.{1,10}到.{1,10}|过去|现在|未来|之后|以前/;
  const 词_对比 = /对比|区别|差异|不同|优点|缺点|优势|劣势|利弊|好坏|取舍|\bvs\b|VS|前者|后者|一方面|另一方面|与其|不如/;
  const 词_层级 = /层级|层次|金字塔|底层|顶层|基础层|核心层|自上而下|从上到下|分为.{0,8}层|由.{1,8}构成/;
  const 词_导图 = /包括|包含|分为|分成|组成|构成|三大|四大|几个方面|要素|维度|板块|类别|由.{1,10}组?成/;
  const 词_数据 = /(%|％|倍|万|亿|￥|¥|\$)/;

  const 单位 = '(?:%|％|倍|万元|亿元|万|亿|千|百|元|块|人|次|天|周|个月|月|小时|分钟|秒|条|家|个|分|名|台|件|公里|km|kg|℃|°|米|万单|单)';
  const 数字 = '(?:-?\\d+(?:\\.\\d+)?)';
  // 时间/阶段的量词：注意「第 1 个月」这种中间带空格的写法
  const 时间量词 = '(?:个?月|季度|天|周|年|阶段|期)';
  const 序数 = new RegExp('第\\s*[一二三四五六七八九十\\d]{1,3}\\s*(?:步|条|点|项|次|' + 时间量词 + ')', 'g');

  // 把「第 1 周」「第 3 步」这类序数挖掉，剩下的数字才算"数据"
  function 去序数(串) {
    return String(串).replace(序数, ' ');
  }

  /* ---------- 清洗 ---------- */

  function 去空白(文本) {
    return String(文本 == null ? '' : 文本).replace(/[\s\u3000]+/g, ' ').trim();
  }

  // 去掉行首的序号 / 圆点 / 破折号等标记，但保留纯文字
  function 去标记(行) {
    return String(行)
      .replace(/^[\s\u3000]*[-*·•●○▪–—>»]+\s*/, '')
      .replace(/^[\s\u3000]*[①②③④⑤⑥⑦⑧⑨⑩⑪⑫]\s*/, '')
      .replace(/^[\s\u3000]*[（(]\s*\d{1,2}\s*[)）]\s*/, '')
      .replace(/^[\s\u3000]*\d{1,2}\s*[、.)）]\s*/, '')
      .replace(/^[\s\u3000]*[一二三四五六七八九十]{1,2}\s*[、.)）]\s*/, '')
      .replace(/^第[一二三四五六七八九十\d]{1,3}(步|条|点|项|阶段)\s*[:：]?\s*/, '')
      .replace(/^(首先|其次|再者|然后|接着|跟着|最后|最终)\s*[,，:：]?\s*/, '')
      .trim();
  }

  /* ---------- 切条目 ---------- */

  function 切条目(文本) {
    let 原文 = String(文本 == null ? '' : 文本).replace(/\r\n?/g, '\n');
    let 行 = 原文.split(/\n+/).map(去空白).filter(Boolean);

    if (行.length <= 1) {
      // 只有一行：先按分号切，再按句号切
      const 唯一 = 行[0] || '';
      let 片 = 唯一.split(/[；;]/).map(去空白).filter(Boolean);
      if (片.length < 2) 片 = 唯一.split(/[。！？!?]/).map(去空白).filter(Boolean);
      if (片.length >= 2) 行 = 片;
    }

    行 = 行.map(去标记).filter((s) => s && s.length > 0);
    return 行;
  }

  // 把一条切成「主标签 + 说明」
  function 分主次(条) {
    const 整 = 去空白(条).replace(/^[，,。：:、\-—\s]+/, '');
    const 洗次 = (s) => s.replace(/^[\s，,。；;：:、\-—]+/, '').replace(/[\s，,。；;：:]+$/, '').trim();
    let m = 整.match(/^(.{2,16}?)[：:]\s*(.+)$/);
    if (m) return { 主: m[1].trim(), 次: 洗次(m[2]) };
    m = 整.match(/^(.{2,16}?)[，,。；;]\s*(.+)$/);
    if (m) return { 主: m[1].trim(), 次: 洗次(m[2]) };
    m = 整.match(/^(.{4,14}?)\s(.+)$/);
    if (m) return { 主: m[1].trim(), 次: 洗次(m[2]) };
    if (整.length > 18) {
      const 主 = 整.slice(0, 15).trim();
      return { 主: 主 + '…', 次: 整.slice(15).trim() };
    }
    return { 主: 整, 次: '' };
  }

  function 取标题(文本, 条目) {
    // 第一行短、且不像一句完整的话 → 当作标题
    const 第一 = (条目[0] || '').trim();
    if (条目.length >= 2 && 第一.length <= 22 && !/[。；;]/.test(第一)) {
      return { 标题: 第一, 条目: 条目.slice(1) };
    }
    const 首句 = (去空白(文本).split(/[。！？\n]/)[0] || '').trim();
    const 标题 = 首句.length > 0 && 首句.length <= 24 ? 首句 : '';
    return { 标题, 条目 };
  }

  /* ---------- 识别 ---------- */

  function 识别(原文本) {
    const 文本 = String(原文本 == null ? '' : 原文本);
    const 条目 = 切条目(文本);
    // 序号标记在 切条目 里就被清掉了，所以判断"是不是分步写的"要看清洗前的原始行
    const 原始行 = 文本.replace(/\r\n?/g, '\n').split(/\n+/).map(去空白).filter(Boolean);
    const 计分 = { 要点: 0, 步骤: 0, 时间线: 0, 对比: 0, 数据: 0, 层级: 0, 导图: 0 };
    const 依据 = [];

    // 步骤：看的是「有几条本身带先后词」，光看全文里出现过一个"先"字不算数
    let 序号数 = 0;
    原始行.forEach((s) => { if (序号词.test(s)) 序号数 += 1; });
    if (序号数 >= 2) { 计分.步骤 += 3 + Math.min(序号数, 5); 依据.push(`识别到 ${序号数} 处先后顺序标记（首先 / 第 N 步 / ①②③）`); }
    let 含先后 = 0;
    条目.forEach((s) => { if (/先|再|然后|接着|跟着|最后|之后|随后/.test(s)) 含先后 += 1; });
    // 只在一两条里出现"先/再"不算流程（"先定人群，再定选题"是一条规则，不是一步操作），
    // 要三条以上都带先后词才当流程看
    if (含先后 >= 3) { 计分.步骤 += 3 + Math.min(含先后 - 2, 3); 依据.push(`${含先后} 条里带着「先 / 再 / 最后」这类先后词`); }
    if (/流程|步骤|工序|路线|动作/.test(文本)) { 计分.步骤 += 2; 依据.push('正文直接出现「流程 / 步骤」这类词'); }

    let 时间数 = 0;
    条目.forEach((s) => {
      if (/(\d{4})\s*年/.test(s) || /(\d{1,2})\s*月\s*(\d{1,2})?\s*日?/.test(s) || /\d{4}\s*[-/.]\s*\d{1,2}/.test(s)
        || new RegExp('第\\s*[一二三四五六七八九十\\d]{1,3}\\s*' + 时间量词).test(s)) 时间数 += 1;
    });
    if (时间数 >= 2) { 计分.时间线 += 3 + Math.min(时间数, 5); 依据.push(`识别到 ${时间数} 处时间 / 阶段标记`); }
    if (词_时间.test(文本)) { 计分.时间线 += 1; 依据.push('正文出现「阶段 / 里程碑 / 规划」这类词'); }

    if (词_对比.test(文本)) { 计分.对比 += 5; 依据.push('正文出现「对比 / 优点 / 缺点 / 而不是」这类对照词'); }

    let 数量 = 0;
    条目.forEach((s) => { if (new RegExp(数字 + '\\s*' + 单位).test(去序数(s))) 数量 += 1; });
    if (数量 >= 2) { 计分.数据 += 2 + Math.min(数量, 6); 依据.push(`有 ${数量} 条要点里带数字（数字 + 单位）`); }
    if (词_数据.test(文本)) { 计分.数据 += 1; 依据.push('正文出现「% / 倍 / 万」这类量词'); }

    if (词_层级.test(文本)) { 计分.层级 += 5; 依据.push('正文出现「层级 / 金字塔 / 底层 / 顶层」这类词'); }
    if (词_导图.test(文本)) { 计分.导图 += 4; 依据.push('正文出现「包括 / 分为 / 由…组成」这类分类词'); }

    // 条目太少的类型降权：对比至少要两栏、导图至少要两个分支
    if (条目.length < 3) { 计分.对比 -= 3; 计分.导图 -= 2; }
    if (条目.length < 2) { 计分.步骤 -= 2; 计分.时间线 -= 2; 计分.数据 -= 2; }

    // 有具体特征就按特征走；一条特征都没命中才落到要点卡（兜底最稳，不硬猜）
    let 最佳 = '要点';
    let 最高 = 0;
    ['步骤', '时间线', '对比', '数据', '层级', '导图'].forEach((名) => {
      if (计分[名] > 最高) { 最高 = 计分[名]; 最佳 = 名; }
    });
    if (最高 < 2) {
      最佳 = '要点';
      依据.push('没有出现顺序 / 时间 / 对照 / 数字 / 层级这些特征，按要点卡排最不容易出错');
    }

    // 并列时给一个"次选"，界面上可以一键换（Napkin 的核心交互就是选一个最像的）
    const 排序 = Object.keys(计分).sort((a, b) => 计分[b] - 计分[a]);
    return { 类型: 最佳, 分数: 计分, 候选: 排序, 依据, 条目数: 条目.length };
  }

  /* ---------- 结构化 ---------- */

  function 结构_条目型(条目) {
    return 条目.map((条) => {
      const { 主, 次 } = 分主次(条);
      return { 标签: 主, 说明: 次 };
    });
  }

  function 结构_时间线(条目) {
    return 条目.map((条, i) => {
      let 时间 = '';
      let m = 条.match(/(\d{4})\s*年(?:\s*(\d{1,2})\s*月)?(?:\s*(\d{1,2})\s*日)?/);
      if (m) {
        时间 = m[1] + '年' + (m[2] ? m[2] + '月' : '') + (m[3] ? m[3] + '日' : '');
      } else {
        m = 条.match(/\d{4}\s*[-/.]\s*\d{1,2}(?:\s*[-/.]\s*\d{1,2})?/);
        if (m) 时间 = m[0].replace(/[-/.]/g, '/');
        else {
          m = 条.match(new RegExp('第\\s*[一二三四五六七八九十\\d]{1,3}\\s*' + 时间量词));
          if (m) 时间 = m[0];
          else {
            m = 条.match(new RegExp('\\d{1,2}\\s*' + 时间量词));
            if (m) 时间 = m[0].replace(/\s+/g, '');
          }
        }
      }
      const 剩 = 时间 ? 条.replace(时间, '').replace(/^[\s，,。：:、\-—]+/, '') : 条;
      const { 主, 次 } = 分主次(剩);
      return { 时间: 时间 || `第 ${i + 1} 阶段`, 标签: 主, 说明: 次 };
    });
  }

  function 结构_对比(条目) {
    // 找「A：xxx」这种块头，或「优点：/缺点：」关键字，切成两栏
    const 栏名 = ['左', '右'];
    const 块 = [[], []];
    let 当前 = 0;
    let 找到分栏 = false;
    let 用前缀分栏 = false;
    const 分栏词 = /^(优点|优势|长处|好处|支持|正面|甲方|A|A方案|方案一|现状|左)[：:、]/;
    const 分栏词2 = /^(缺点|劣势|短处|坏处|反对|负面|乙方|B|B方案|方案二|目标|右)[：:、]/;
    条目.forEach((条) => {
      if (分栏词2.test(条)) { 当前 = 1; 找到分栏 = true; 块[1].push(条.replace(分栏词2, '').trim() || 条); return; }
      if (分栏词.test(条)) { 当前 = 0; 找到分栏 = true; 块[0].push(条.replace(分栏词, '').trim() || 条); return; }
      块[当前].push(条);
    });
    // 没有「优点/缺点」这种显式块头时，看有没有重复出现的前缀（例如「自己拍：…」×3、「找人拍：…」×3）
    if (!找到分栏) {
      const 对 = 条目.map((s) => {
        const m = String(s).match(/^(.{1,10}?)\s*[：:]\s*(.+)$/);
        return m ? { 头: m[1].trim(), 尾: m[2].trim() } : null;
      });
      const 计数 = new Map();
      对.forEach((x) => { if (x) 计数.set(x.头, (计数.get(x.头) || 0) + 1); });
      const 常见 = [...计数.entries()].filter(([, n]) => n >= 2).sort((a, b) => b[1] - a[1]).map(([k]) => k);
      if (常见.length === 2 && 对.every((x) => x && 常见.indexOf(x.头) >= 0)) {
        块[0] = [];
        块[1] = [];
        栏名[0] = 常见[0];
        栏名[1] = 常见[1];
        对.forEach((x) => { 块[常见.indexOf(x.头)].push(x.尾); });
        找到分栏 = true;
        用前缀分栏 = true;
      }
    }
    if (!找到分栏) {
      const 半 = Math.ceil(条目.length / 2);
      块[0] = 条目.slice(0, 半);
      块[1] = 条目.slice(半);
      栏名[0] = '一方面';
      栏名[1] = '另一方面';
    } else if (!用前缀分栏) {
      const 左头 = 条目.find((s) => 分栏词.test(s));
      const 右头 = 条目.find((s) => 分栏词2.test(s));
      栏名[0] = 左头 ? (左头.match(分栏词) || [''])[0].replace(/[：:、]/g, '') : 'A';
      栏名[1] = 右头 ? (右头.match(分栏词2) || [''])[0].replace(/[：:、]/g, '') : 'B';
    }
    return {
      左: { 标题: 栏名[0], 条目: 块[0].map((s) => 分主次(s)).filter((x) => x.主) },
      右: { 标题: 栏名[1], 条目: 块[1].map((s) => 分主次(s)).filter((x) => x.主) }
    };
  }

  function 结构_数据(条目) {
    const 出 = [];
    条目.forEach((原条) => {
      const 条 = 去序数(原条);
      const m = 条.match(new RegExp('(' + 数字 + ')\\s*(' + 单位 + ')?'));
      if (!m) return;
      const 数值 = m[1];
      const 单位值 = (m[2] || '').replace('％', '%');
      let 标签 = 条.replace(m[0], ' ').replace(/^[\s，,。：:、\-—]+|[\s，,。：:、\-—]+$/g, '');
      const { 主, 次 } = 分主次(标签);
      出.push({ 数值, 单位: 单位值, 标签: 主 || '指标', 备注: 次 });
    });
    return 出;
  }

  function 结构_导图(条目) {
    if (条目.length === 0) return { 中心: '', 分支: [] };
    const { 标题, 条目: 正条目 } = 取标题('', 条目);
    const 中心 = 标题 || '主题';
    const 余 = 标题 ? 正条目 : 条目.slice(1);
    const 分支 = [];
    // 一条里带「、」或「，」的并列项 → 当成分支的子项
    余.forEach((条) => {
      const { 主, 次 } = 分主次(条);
      let 子 = [];
      if (次) 子 = 次.split(/[、，,]/).map(去空白).filter(Boolean);
      if (!次 && /[、，,]/.test(主)) {
        const 片 = 主.split(/[、，,]/).map(去空白).filter(Boolean);
        if (片.length >= 2) { 分支.push({ 标签: 片[0], 子: 片.slice(1) }); return; }
      }
      分支.push({ 标签: 主, 子: 子.slice(0, 3) });
    });
    return { 中心, 分支 };
  }

  function 结构化(原文本, 指定类型) {
    const 文本 = String(原文本 == null ? '' : 原文本);
    const 判 = 识别(文本);
    const 类型 = 指定类型 && 指定类型 !== '自动' ? 指定类型 : 判.类型;
    const 条目全 = 切条目(文本);
    const { 标题, 条目 } = 取标题(文本, 条目全);
    const 数据 = { 标题, 副标题: '' };

    if (类型 === '步骤') {
      数据.类型 = '步骤';
      数据.条目 = 结构_条目型(条目);
    } else if (类型 === '时间线') {
      数据.类型 = '时间线';
      数据.条目 = 结构_时间线(条目);
    } else if (类型 === '对比') {
      数据.类型 = '对比';
      数据.对比 = 结构_对比(条目);
    } else if (类型 === '数据') {
      数据.类型 = '数据';
      数据.条目 = 结构_数据(条目);
      if (数据.条目.length === 0) { 数据.类型 = '要点'; 数据.条目 = 结构_条目型(条目); }
    } else if (类型 === '层级') {
      数据.类型 = '层级';
      数据.条目 = 结构_条目型(条目);
    } else if (类型 === '导图') {
      数据.类型 = '导图';
      数据.导图 = 结构_导图(条目全);
    } else {
      数据.类型 = '要点';
      数据.条目 = 结构_条目型(条目);
    }
    数据.判据 = 判;
    return 数据;
  }

  const 引擎 = {
    切条目, 去标记, 分主次, 取标题, 识别, 结构化,
    词表: { 序号词, 词_流程, 词_时间, 词_对比, 词_层级, 词_导图 }
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = 引擎;
  else 全局.图说引擎 = 引擎;
})(typeof self !== 'undefined' ? self : globalThis);
