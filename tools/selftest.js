    const svg = 出.svg;
    const 问题 = [];
    if (!/^<svg[\s\S]*<\/svg>$/.test(svg.trim())) 问题.push('不是完整 svg');
    if (/NaN|undefined|Infinity|\[object/.test(svg)) 问题.push('出现了 NaN/undefined');
    const 开 = (svg.match(/<text[\s>]/g) || []).length;
    const 闭 = (svg.match(/<\/text>/g) || []).length;
    if (开 !== 闭) 问题.push(`text 标签不配对（开 ${开} 闭 ${闭}）`);
    if (/<\/(rect|circle|line|path)>/.test(svg)) 问题.push('自闭合标签被写成了成对标签');
